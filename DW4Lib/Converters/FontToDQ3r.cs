namespace DW4Lib.Converters;

/// <summary>
/// Converts fonts for DW4→DQ3r localization.
/// Handles English font data for replacing Japanese script in DQ3r SNES.
/// 
/// DQ3r SNES uses:
/// - 4bpp tile format (SNES standard)
/// - Variable width fonts stored in groups
/// - Font groups define: size, width, height, data offset
/// 
/// For English, we need:
/// - 8x8 or 8x16 pixel characters
/// - A-Z, a-z, 0-9, punctuation
/// - Variable width support for proper spacing
/// </summary>
public static class FontToDQ3r {
	/// <summary>
	/// English font character definition.
	/// </summary>
	public class FontCharacter {
		/// <summary>Character this represents.</summary>
		public char Character { get; set; }

		/// <summary>Width in pixels (1-16).</summary>
		public int Width { get; set; }

		/// <summary>Height in pixels (1-16).</summary>
		public int Height { get; set; }

		/// <summary>4bpp tile data.</summary>
		public byte[] TileData { get; set; } = [];

		/// <summary>Table file code for this character.</summary>
		public int TableCode { get; set; }
	}

	/// <summary>
	/// English font configuration for DQ3r.
	/// </summary>
	public static class EnglishFontConfig {
		/// <summary>Standard character width.</summary>
		public const int DefaultWidth = 8;

		/// <summary>Standard character height.</summary>
		public const int DefaultHeight = 12;

		/// <summary>First character group table code (replaces Japanese).</summary>
		public const int CharacterGroupBase = 0x0200;

		/// <summary>Control code base.</summary>
		public const int ControlCodeBase = 0x00AB;
	}

