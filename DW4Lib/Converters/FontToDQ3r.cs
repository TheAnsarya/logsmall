	/// <summary>
	/// Convert 1bpp glyph to 4bpp SNES format.
	/// SNES 4bpp tiles are interleaved: rows of planes 0-1, then planes 2-3.
	/// For a single color font, we only use plane 0.
	/// </summary>
	public static byte[] Convert1bppTo4bpp(byte[] glyph1bpp) {
		// SNES 4bpp tile: 8x8 = 32 bytes per tile
		// For 8x12, we need 2 tiles (16 rows, use first 12)
		int tilesNeeded = (glyph1bpp.Length + 7) / 8;
		byte[] result = new byte[tilesNeeded * 32];

		for (int tile = 0; tile < tilesNeeded; tile++) {
			int srcOffset = tile * 8;
			int dstOffset = tile * 32;

			for (int row = 0; row < 8 && srcOffset + row < glyph1bpp.Length; row++) {
				byte rowData = glyph1bpp[srcOffset + row];

				// Plane 0 (bit 0) - first 16 bytes, even positions
				result[dstOffset + row * 2] = rowData;
				// Plane 1 (bit 1) - first 16 bytes, odd positions
				result[dstOffset + row * 2 + 1] = 0; // Keep plane 1 empty for single color
				// Planes 2-3 at offset 16 - keep zeros for single color
			}
		}

		return result;
	}

	/// <summary>
	/// Generate complete English font data for DQ3r.
	/// Returns dictionary of character -> 4bpp tile data.
	/// </summary>
	public static Dictionary<char, byte[]> GenerateEnglishFontTiles() {
		var result = new Dictionary<char, byte[]>();

		foreach (var kvp in AsciiToTableCode) {
			char c = kvp.Key;
			byte[] glyph1bpp = Create1bppGlyph(c);
			byte[] glyph4bpp = Convert1bppTo4bpp(glyph1bpp);
			result[c] = glyph4bpp;
		}

		return result;
	}
