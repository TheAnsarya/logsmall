	/// <summary>
	/// Get character width for variable-width font.
	/// </summary>
	public static int GetCharacterWidth(char c) {
		return CharacterWidths.TryGetValue(c, out int width) ? width : 6;
	}

	/// <summary>
	/// Get table code for a character.
	/// </summary>
	public static int GetTableCode(char c) {
		return AsciiToTableCode.TryGetValue(c, out int code) ? code : AsciiToTableCode[' '];
	}

	/// <summary>
	/// Get character from table code.
	/// </summary>
	public static char GetCharacter(int code) {
		return TableCodeToAscii.TryGetValue(code, out char c) ? c : ' ';
	}

	/// <summary>
	/// Check if a code is a control code.
	/// </summary>
	public static bool IsControlCode(int code) {
		return code >= 0x00AB && code <= 0x00FF;
	}

